"""The generated demo song as a **machine-testing fixture** (not for dancing).

Decided 2026-10-18: the procedurally generated track (:mod:`parapara.audio.synth`)
is not part of the game's song library and is never offered to players; it
exists because its beat map is known *exactly*, which makes it the ground
truth for automated tests of beat detection, the suitability check, song
import, the beat-check app and (later) clap detection. Tests generate it into
temporary folders with :func:`make_demo_song`; nothing is written to
``assets/``.

Songs for people to dance to are the CC BY demo tracks
(``parapara-fetch-demo-songs``) and the players' own imports.
"""

from __future__ import annotations

from pathlib import Path

from parapara.audio.song import BeatMapInfo, License, Song
from parapara.audio.synth import DemoSong, render_demo_song, write_wav

DEMO_ID = "test-demo"


def demo_song_metadata(track: DemoSong, directory: Path = Path(".")) -> Song:
    """The :class:`Song` describing a rendered track (exact beat map)."""
    return Song(
        id=DEMO_ID,
        title="Generated test track (machine testing only)",
        artist="parapara.audio.synth",
        audio="demo.wav",
        license=License("project-generated (no third-party rights)"),
        source=f"generated by parapara.audio.synth.render_demo_song(bpm={track.bpm})",
        bpm=track.bpm,
        first_beat_s=track.first_beat_s,
        routine_start_beat=track.routine_start_beat,
        duration_beats=track.duration_beats,
        beat_map=BeatMapInfo(
            "generated",
            verified=True,
            drift_ms=0.0,
            notes="exact by construction; sections " + str(track.sections),
        ),  # fmt: skip
        directory=directory,
    )


def make_demo_song(library: Path, bpm: float = 150.0, phrases: int = 2) -> Song:
    """Render the track into ``library/test-demo/`` (a temporary test folder)."""
    track = render_demo_song(bpm=bpm, phrases=phrases)
    directory = library / DEMO_ID
    write_wav(directory / "demo.wav", track.samples, track.sample_rate)
    song = demo_song_metadata(track, directory)
    song.save()
    return song
